#!/bin/bash

#########################################
# VALIDACIÓN IPv4
#########################################

isIPv4() {

    [[ $1 =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]] || return 1

    IFS='.' read -r o1 o2 o3 o4 <<< "$1"

    for o in $o1 $o2 $o3 $o4
    do
        [ "$o" -gt 255 ] && return 1
    done

    return 0
}

#########################################
# VALIDACIÓN IPv6
#########################################

isIPv6() {

    [[ "$1" == *:* ]]
}

#########################################
# Detectar familia
#########################################

detectFamily() {

    if isIPv6 "$1"
    then
        echo "inet6"
    else
        echo "inet"
    fi

}
